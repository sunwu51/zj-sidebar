#!/usr/bin/env bash
# Install zj-sidebar (a zellij plugin) on Linux / macOS.
#
#   curl -fsSL https://raw.githubusercontent.com/sunwu51/zj-sidebar/main/install.sh | bash
#   ./install.sh [--from-source] [--dist DIR] [--config-dir DIR] [--version vX.Y.Z]
#
# Installs <zellij config dir>/plugins/zj-sidebar.wasm, the layout
# <zellij config dir>/layouts/sidebar.kdl and the native helper
# ${XDG_DATA_HOME:-~/.local/share}/zj-sidebar/zjsb-helper. It never edits your config.kdl.
#
# Environment: ZJSB_REPO (owner/name), ZJSB_VERSION, ZJSB_BASE_URL (download base),
#              ZELLIJ_CONFIG_DIR
set -euo pipefail

REPO="${ZJSB_REPO:-sunwu51/zj-sidebar}"
VERSION="${ZJSB_VERSION:-latest}"
BASE_URL="${ZJSB_BASE_URL:-}"
FROM_SOURCE=0
DIST=""
CONFIG_DIR="${ZELLIJ_CONFIG_DIR:-}"

while [ $# -gt 0 ]; do
  case "$1" in
    --from-source) FROM_SOURCE=1 ;;
    --dist) DIST="$2"; shift ;;
    --config-dir) CONFIG_DIR="$2"; shift ;;
    --version) VERSION="$2"; shift ;;
    -h|--help) sed -n '2,10p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) echo "unknown option: $1" >&2; exit 2 ;;
  esac
  shift
done

say() { printf '==> %s\n' "$*"; }
die() { printf 'error: %s\n' "$*" >&2; exit 1; }

if [ -z "$CONFIG_DIR" ] && command -v zellij >/dev/null 2>&1; then
  # ask zellij itself: it picks the first of ~/.config/zellij, the platform default, /etc/zellij
  CONFIG_DIR=$(zellij setup --check 2>/dev/null | sed -n 's/^\[CONFIG DIR\]: "\(.*\)"$/\1/p' | head -1 || true)
fi
if [ -z "$CONFIG_DIR" ]; then
  CONFIG_DIR="${XDG_CONFIG_HOME:-$HOME/.config}/zellij"
fi
DATA_DIR="${XDG_DATA_HOME:-$HOME/.local/share}/zj-sidebar"

case "$(uname -s)-$(uname -m)" in
  Linux-x86_64)         TARGET=x86_64-unknown-linux-musl ;;
  Linux-aarch64|Linux-arm64) TARGET=aarch64-unknown-linux-musl ;;
  Darwin-x86_64)        TARGET=x86_64-apple-darwin ;;
  Darwin-arm64)         TARGET=aarch64-apple-darwin ;;
  *) die "unsupported platform $(uname -s)-$(uname -m)" ;;
esac

WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT

if [ -n "$DIST" ]; then
  say "using local files from $DIST"
  cp "$DIST/zj-sidebar.wasm" "$WORK/zj-sidebar.wasm"
  cp "$DIST/zjsb-helper-$TARGET" "$WORK/zjsb-helper"
elif [ "$FROM_SOURCE" = 1 ]; then
  command -v cargo >/dev/null || die "cargo not found (install Rust from https://rustup.rs)"
  SRC=$(cd "$(dirname "$0")" && pwd)
  [ -f "$SRC/Cargo.toml" ] || die "--from-source must be run from a checkout of the repository"
  say "building the plugin (wasm32-wasip1)"
  rustup target add wasm32-wasip1 >/dev/null 2>&1 || true
  cargo build --release --target wasm32-wasip1 --manifest-path "$SRC/Cargo.toml"
  cp "$SRC/target/wasm32-wasip1/release/zj-sidebar.wasm" "$WORK/zj-sidebar.wasm"
  say "building the helper ($TARGET)"
  HOST=$(rustc -vV | sed -n 's/^host: //p')
  cargo build --release --target "$HOST" --manifest-path "$SRC/helper/Cargo.toml"
  cp "$SRC/helper/target/$HOST/release/zjsb-helper" "$WORK/zjsb-helper"
else
  if [ -z "$BASE_URL" ]; then
    if [ "$VERSION" = latest ]; then
      BASE_URL="https://github.com/$REPO/releases/latest/download"
    else
      BASE_URL="https://github.com/$REPO/releases/download/$VERSION"
    fi
  fi
  fetch() { # url dest
    if command -v curl >/dev/null; then curl -fsSL "$1" -o "$2"; else wget -q "$1" -O "$2"; fi
  }
  say "downloading from $BASE_URL"
  fetch "$BASE_URL/zj-sidebar.wasm" "$WORK/zj-sidebar.wasm" || die "download failed (no release yet? try --from-source)"
  fetch "$BASE_URL/zjsb-helper-$TARGET" "$WORK/zjsb-helper" || die "no helper binary for $TARGET"
  if fetch "$BASE_URL/SHA256SUMS" "$WORK/SHA256SUMS" 2>/dev/null; then
    if command -v sha256sum >/dev/null; then SUM="sha256sum"; else SUM="shasum -a 256"; fi
    check() { # file asset-name
      want=$(awk -v n="$2" '{ f = $2; sub(/^\*/, "", f); if (f == n) print $1 }' "$WORK/SHA256SUMS")
      have=$($SUM "$1" | awk '{print $1}')
      [ -n "$want" ] && [ "$want" = "$have" ] || die "checksum mismatch for $2"
    }
    check "$WORK/zj-sidebar.wasm" zj-sidebar.wasm
    check "$WORK/zjsb-helper" "zjsb-helper-$TARGET"
    say "checksums ok"
  fi
fi

PLUGINS="$CONFIG_DIR/plugins"
LAYOUTS="$CONFIG_DIR/layouts"
mkdir -p "$PLUGINS" "$LAYOUTS" "$DATA_DIR"
install -m 0644 "$WORK/zj-sidebar.wasm" "$PLUGINS/zj-sidebar.wasm"
install -m 0755 "$WORK/zjsb-helper" "$DATA_DIR/zjsb-helper"
# a binary downloaded through a browser would be quarantined on macOS
if [ "$(uname -s)" = Darwin ]; then xattr -d com.apple.quarantine "$DATA_DIR/zjsb-helper" 2>/dev/null || true; fi

PLUGIN_URL="file:$PLUGINS/zj-sidebar.wasm"
cat > "$LAYOUTS/sidebar.kdl" <<EOF
// zj-sidebar: tab list on the left, grouped by directory. Generated by install.sh.
layout {
    default_tab_template {
        pane split_direction="vertical" {
            pane size=32 borderless=true {
                plugin location="$PLUGIN_URL"
            }
            pane
        }
        pane size=1 borderless=true {
            plugin location="zellij:status-bar"
        }
    }
}
EOF

say "installed: $PLUGINS/zj-sidebar.wasm, $LAYOUTS/sidebar.kdl, $DATA_DIR/zjsb-helper"
cat <<EOF

Try it now:
    zellij --layout sidebar

Make it the default: add this line to $CONFIG_DIR/config.kdl
    default_layout "sidebar"

Optional keybinding (Alt+d toggles the git/sessions panel), inside
keybinds { shared_except "locked" { ... } } in config.kdl:
    bind "Alt d" { MessagePlugin "$PLUGIN_URL" { name "toggle_panel"; }; }
(or just click "git · sessions" at the bottom of the left sidebar)

On first start, zellij asks the sidebar for permissions: click it and press y.
EOF
